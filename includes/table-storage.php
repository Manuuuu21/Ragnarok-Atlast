<?php
const BUILDER_TABLE_FILES = [
    'itemDATA' => 'item-data.js',
    'monsterDATA' => 'monster-data.js',
    'mapDATA' => 'map-data.js',
];
const BUILDER_TABLE_LIMIT = 128 * 1024 * 1024;

function save_builder_table($directory, $name, $json) {
    if (!isset(BUILDER_TABLE_FILES[$name])) {
        throw new InvalidArgumentException('Unknown data table.');
    }
    if (strlen($json) > BUILDER_TABLE_LIMIT) {
        throw new LengthException('A generated table must be smaller than 128 MB.');
    }
    // Receive JSON data, never executable JavaScript or a caller-supplied path.
    // json_last_error also supports the PHP 7.1 runtime bundled by OpenServer.
    $records = json_decode($json, false, 64);
    if (json_last_error() !== JSON_ERROR_NONE) {
        throw new InvalidArgumentException('The generated table is not valid JSON.');
    }
    if (!($records instanceof stdClass) || !count(get_object_vars($records))) {
        throw new InvalidArgumentException('Only populated data tables can be saved.');
    }
    foreach ($records as $id => $record) {
        if (!($record instanceof stdClass) || !isset($record->id) || (!is_int($record->id) && !is_string($record->id)) || (string) $record->id !== (string) $id) {
            throw new InvalidArgumentException('Each table entry must have an ID matching its key.');
        }
    }
    unset($records, $record);
    $json = str_replace(['<', "\u{2028}", "\u{2029}"], ['\\u003c', '\\u2028', '\\u2029'], $json);
    $content = "// Generated by Ragnarok Atlas. Renewal source data; omitted server fields remain omitted.\nconst $name = $json;\n";
    if (!is_dir($directory) && !@mkdir($directory, 0775, true) && !is_dir($directory)) {
        throw new RuntimeException('Could not create search-app/lib/. Check the folder permissions.');
    }
    $directory = realpath($directory);
    if ($directory === false || !is_writable($directory)) {
        throw new RuntimeException('search-app/lib/ is not writable. Check the folder permissions.');
    }
    $filename = BUILDER_TABLE_FILES[$name];
    $target = $directory . DIRECTORY_SEPARATOR . $filename;
    if (is_link($target)) {
        throw new RuntimeException("Cannot replace $filename because it is a symbolic link.");
    }
    // Stage beside the destination so a failed write never truncates its old file.
    $temporary = @tempnam($directory, '.build-');
    if ($temporary === false || dirname($temporary) !== $directory) {
        if ($temporary !== false) @unlink($temporary);
        throw new RuntimeException('Could not stage the generated table in search-app/lib/.');
    }
    try {
        if (@file_put_contents($temporary, $content, LOCK_EX) !== strlen($content)) {
            throw new RuntimeException("Could not write $filename. Check free disk space and folder permissions.");
        }
        // Preserve existing read permissions when replacing a table.
        @chmod($temporary, is_file($target) ? fileperms($target) & 0777 : 0644);
        if (!@rename($temporary, $target)) {
            throw new RuntimeException("Could not replace $filename. Check whether it is read-only or locked.");
        }
    } finally {
        if (is_file($temporary)) @unlink($temporary);
    }
    return $filename;
}
